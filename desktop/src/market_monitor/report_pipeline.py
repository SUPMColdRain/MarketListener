# --------------------------------------------------------------------------
# 证券白名单缓存（从 silver parquet 读取真实证券名称）
# --------------------------------------------------------------------------
_WHITELIST_CACHE: dict[str, tuple[set[str], set[str], set[str], "re.Pattern[str] | None", float]] = {}
_WHITELIST_LOCK = threading.Lock()
_WHITELIST_TTL_SECONDS = 900


def _default_data_root() -> Path:
    return Path(__file__).resolve().parents[3] / "data_control"


def _compile_whitelist_pattern(names: set[str]) -> "re.Pattern[str] | None":
    candidates = sorted((name for name in names if len(name) >= 2), key=len, reverse=True)
    if not candidates:
        return None
    parts: list[str] = []
    for name in candidates:
        parts.append(r"(?<![A-Za-z0-9])" + re.escape(name) + r"(?![A-Za-z0-9])")
    return re.compile("|".join(parts))


def _load_whitelist(
    data_root: Path | None = None,
) -> tuple[set[str], set[str], set[str], "re.Pattern[str] | None"]:
    root = Path(data_root) if data_root is not None else _default_data_root()
    key = str(root.resolve())
    now = time.monotonic()
    with _WHITELIST_LOCK:
        cached = _WHITELIST_CACHE.get(key)
        if cached is not None and now - cached[4] < _WHITELIST_TTL_SECONDS:
            return cached[0], cached[1], cached[2], cached[3]
    companies: set[str] = set(_KNOWN_COMPANIES)
    products: set[str] = set(_KNOWN_PRODUCTS)
    materials: set[str] = set(_KNOWN_MATERIALS)
    silver = root / "silver"
    if silver.is_dir():
        try:
            import duckdb  # type: ignore[import-not-found]

            con = duckdb.connect()
            glob_pattern = str(silver / "**" / "*.parquet").replace("\\", "/")
            query = (
                "SELECT DISTINCT market, asset_type, "
                "json_extract_string(bar_json, '$.name') AS name "
                "FROM read_parquet('" + glob_pattern + "', filename=true) "
                "WHERE bar_json IS NOT NULL "
                "AND json_extract_string(bar_json, '$.name') IS NOT NULL"
            )
            for market, asset_type, name in con.execute(query).fetchall():
                raw = str(name or "").strip()
                if not raw:
                    continue
                if asset_type == "STOCK":
                    companies.add(raw)
                    companies.add(re.sub(r"-[WH]$", "", raw))
                else:
                    if "." in raw or len(raw) > 24:
                        continue
                    if re.fullmatch(r"[A-Za-z0-9·\-_]{1,3}", raw):
                        continue
                    if raw.endswith("指数") or any(token in raw for token in _INDEX_NAME_TOKENS):
                        continue
                    if re.fullmatch(r"[\u4e00-\u9fffA-Za-z]{2,10}\d{2,4}", raw):
                        continue
                    if raw.startswith(_ENTITY_EXCHANGE_PREFIXES):
                        continue
                    if raw in _PRODUCT_STOPWORDS:
                        continue
                    products.add(raw)
                    cleaned = re.sub(r"(连续|加权|主力|主连)$", "", raw)
                    cleaned = re.sub(r"[A-Za-z0-9.·\-]+$", "", cleaned).strip()
                    if cleaned and len(cleaned) >= 2:
                        if cleaned.endswith("指数") or any(token in cleaned for token in _INDEX_NAME_TOKENS):
                            continue
                        if re.fullmatch(r"[\u4e00-\u9fffA-Za-z]{2,10}\d{2,4}", cleaned):
                            continue
                        if cleaned.startswith(_ENTITY_EXCHANGE_PREFIXES):
                            continue
                        if cleaned in _PRODUCT_STOPWORDS:
                            continue
                        products.add(cleaned)
        except Exception:  # noqa: BLE001 - 白名单缺失时退化为精选名单
            pass
    pattern = _compile_whitelist_pattern(companies | products | materials)
    with _WHITELIST_LOCK:
        _WHITELIST_CACHE[key] = (companies, products, materials, pattern, time.monotonic())
    return companies, products, materials, pattern


def _utcnow() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def _clean_text(text: str) -> str:
    text = re.sub(r"[\x00-\x08\x0b\x0c\x0e-\x1f]", "", text)
    text = re.sub(r"[ \t\u3000]+", " ", text)
    return text.strip()


def _chain_scores(text: str, title: str) -> Counter[str]:
    """对一段文本（标题加权）计算产业链命中分数。"""

    scores: Counter[str] = Counter()
    body = text or ""
    for alias, chain in _ALIAS_CHAIN:
        if alias in title:
            scores[chain] += 3
        if alias and alias in body:
            scores[chain] += 1
    return scores


_SENTENCE_SPLIT_RE = re.compile(r"[。！？!?；;\n]+")


def _stage_for_position(sentence: str, page_text: str, position: int) -> str:
    for stage, markers in _STAGE_MARKERS:
        for marker in markers:
            if marker in sentence:
                return stage
    window = page_text[max(0, position - 120) : position + 120]
    best: tuple[str, int] = ("中游", 10**9)
    for stage, markers in _STAGE_MARKERS:
        for marker in markers:
            index = window.find(marker)
            if index < 0:
                continue
            distance = abs(index - 120)
            if distance < best[1]:
                best = (stage, distance)
    return best[0]


def _evidence_window(
    text: str,
    position: int,
    sentences: list[tuple[int, int]],
    width: int = MAX_EVIDENCE_CHARS,
) -> str:
    start = 0
    end = len(text)
    for sentence_start, sentence_end in sentences:
        if sentence_start <= position < sentence_end:
            start, end = sentence_start, sentence_end
            break
    else:
        start = max(0, position - width // 3)
        end = min(len(text), position + 2 * width // 3)
    if end - start > width:
        mid = position - start
        cut = width // 2
        start = start + max(0, mid - cut)
        end = min(end, start + width)
    evidence = text[start:end].strip()
    evidence = re.sub(r"\s+", " ", evidence)
    return evidence[:width]


def _normalize_entity(name: str, entity_type: str) -> str:
    name = name.strip(" 　、，。：:；;（）()【】[]《》“”\"'·")
    if entity_type == "COMPANY":
        name = re.sub(r"股份有限公司$", "股份", name)
        for suffix in (
            "控股集团有限公司", "集团有限公司", "有限责任公司",
            "有限公司", "集团公司", "股份公司",
        ):
            if name.endswith(suffix) and len(name) - len(suffix) >= 4:
                name = name[: -len(suffix)].strip()
                break
        name = re.sub(r"（(?:股份|集团|控股|科技|有限|公司).*?）", "", name)
        name = re.sub(r"\((?:股份|集团|控股|科技|有限|公司).*?\)", "", name)
        name = name.strip("（）() ")
    return name


def _is_stop_entity(name: str, entity_type: str, strict: bool = False) -> bool:
    if not name or len(name) < 2:
        return True
    if entity_type == "COMPANY":
        if name in _COMPANY_STOPWORDS or name in _COMMON_WORDS or name in _CHAIN_ALIAS_SET:
            return True
        if strict:
            return False
        if any(keyword in name for keyword in _COMPANY_BAD_WORDS):
            return True
    elif entity_type in {"PRODUCT", "RAW_MATERIAL", "SERVICE"}:
        if name in _COMMON_WORDS or name in _CHAIN_ALIAS_SET or name in _PRODUCT_STOPWORDS:
            return True
        if strict:
            return False
        if re.fullmatch(r"[\d.%-]+", name):
            return True
        if len(name) > 9:
            return True
        if name.startswith(_ENTITY_EXCHANGE_PREFIXES):
            return True
        if any(token in name for token in _PHRASE_STOP_TOKENS):
            return True
        if any(keyword in name for keyword in _PRODUCT_BAD_WORDS):
            return True
    return False


def _detect_chains_in_text(text: str, title: str, limit: int = 5) -> list[str]:
    scores = _chain_scores(text, title)
    return [chain for chain, _ in scores.most_common(limit) if chain != "其他"]


def _detect_dates(text: str) -> list[str]:
    dates: list[str] = []
    for year, month, day in _DATE_RE.findall(text):
        value = f"{year}-{int(month):02d}-{int(day):02d}"
        if value not in dates:
            dates.append(value)
    if len(dates) >= 10:
        return dates[:10]
    return dates


def _chunk_pages(pages: list[str]) -> list[dict[str, Any]]:
    """把每页文本切成约 2000 字符、带重叠的块。"""

    chunks: list[dict[str, Any]] = []
    for page_index, page_text in enumerate(pages, start=1):
        if not page_text:
            continue
        start = 0
        while start < len(page_text):
            end = start + CHUNK_CHARS
            chunk_text = page_text[start:end]
            chunks.append(
                {
                    "chunk_id": f"p{page_index}-{len(chunks)}",
                    "page": page_index,
                    "chars": len(chunk_text),
                    "text": chunk_text,
                }
            )
            if end >= len(page_text):
                break
            start = end - CHUNK_OVERLAP
    return chunks


_CITATION_RE = re.compile(
    r"^\s*(?:资料来源|数据来源|图片来源|来源)\s*[:：]?"
    r"|(?:证券|期货|基金|银行)[-–—·][^。\n]{0,80}"
    r"|^\s*\d+\s*[.、]\s*[^。\n]{0,80}(?:报告|白皮书|策略|点评|深度|月报|周报|年报|季报|专题|研究|纪要|系列|概述|展望)"
)


def _is_citation_sentence(sentence: str) -> bool:
    """过滤“资料来源”页脚与研报标题引用行，避免把引用当产业链事实。"""

    return bool(_CITATION_RE.search(sentence or ""))


def _extract_facts_from_page(
    page_index: int,
    page_text: str,
    chains: list[str],
    primary_chain: str,
    whitelist: tuple[set[str], set[str], set[str], "re.Pattern[str] | None"] | None = None,
) -> tuple[list[dict[str, Any]], list[dict[str, str]]]:
    """从单页文本抽取公司 / 产品 / 原材料 / 服务事实与同页共现关系。"""

    companies: set[str] = set()
    products: set[str] = set()
    materials: set[str] = set()
    pattern: "re.Pattern[str] | None" = None
    if whitelist is not None:
        companies, products, materials, pattern = whitelist

    facts: list[dict[str, Any]] = []
    positions: list[tuple[str, str, int]] = []
    claimed: list[tuple[int, int]] = []
    cooccurrences: list[dict[str, str]] = []

    sentences: list[tuple[int, int]] = []
    sentence_start = 0
    for match in _SENTENCE_SPLIT_RE.finditer(page_text):
        if match.start() > sentence_start:
            sentences.append((sentence_start, match.start()))
        sentence_start = match.end()
    if sentence_start < len(page_text):
        sentences.append((sentence_start, len(page_text)))

    def chain_for(position: int) -> str:
        window = page_text[max(0, position - 80) : position + 80]
        best = primary_chain
        best_distance = 10**9
        for alias, chain in _ALIAS_CHAIN:
            index = window.find(alias)
            if index >= 0 and abs(index - 80) < best_distance:
                best = chain
                best_distance = abs(index - 80)
        return best

    def make_fact(
        entity: str,
        entity_type: str,
        position: int,
        source: str,
    ) -> dict[str, Any] | None:
        normalized = _normalize_entity(entity, entity_type)
        if not normalized or len(normalized) < 2:
            return None
        if _is_stop_entity(normalized, entity_type, strict=(source == "whitelist")):
            return None
        sentence_bounds = (0, len(page_text))
        for sent_start, sent_end in sentences:
            if sent_start <= position < sent_end:
                sentence_bounds = (sent_start, sent_end)
                break
        if _is_citation_sentence(page_text[sentence_bounds[0] : sentence_bounds[1]]):
            return None
        chain = chain_for(position)
        confidence = 0.62
        if chain == primary_chain:
            confidence += 0.15
        if any(alias in page_text[max(0, position - 120) : position + 120] for alias, _ in _ALIAS_CHAIN if _ == chain):
            confidence += 0.05
        if entity_type == "COMPANY":
            confidence += 0.1
        if source == "whitelist":
            confidence += 0.08
        stage = _stage_for_position(page_text[sentence_bounds[0] : sentence_bounds[1]], page_text, position)
        return {
            "entity": normalized,
            "entity_type": entity_type,
            "chain": chain,
            "stage": stage,
            "evidence": _evidence_window(page_text, position, sentences),
            "page": page_index,
            "confidence": round(min(confidence, 0.95), 2),
        }

    def add_candidate(
        entity: str,
        start_pos: int,
        end_pos: int,
        entity_type: str,
        source: str,
    ) -> None:
        if end_pos <= start_pos or start_pos < 0 or end_pos > len(page_text):
            return
        for claimed_start, claimed_end in claimed:
            if start_pos < claimed_end and claimed_start < end_pos:
                return
        claimed.append((start_pos, end_pos))
        fact = make_fact(entity, entity_type, start_pos, source)
        if fact is not None:
            facts.append(fact)
            positions.append((fact["entity"], entity_type, start_pos))

    # 1. 白名单（真实证券 + 精选公司 / 产品 / 原材料），长名优先
    if pattern is not None:
        for match in pattern.finditer(page_text):
            name = match.group(0)
            if name in companies:
                add_candidate(name, match.start(), match.end(), "COMPANY", "whitelist")
            elif name in materials and name not in products:
                add_candidate(name, match.start(), match.end(), "RAW_MATERIAL", "whitelist")
            elif name in products or name in materials:
                add_candidate(name, match.start(), match.end(), "PRODUCT", "whitelist")

    # 2. 强后缀公司名（要求前后边界，避免“年美畅股份”这类短语尾巴）
    for match in _COMPANY_RE.finditer(page_text):
        add_candidate(match.group(1), match.start(1), match.end(1), "COMPANY", "regex")

    # 3. 引号 / 书名号内的产品（仅接受白名单实体，避免政策名/短语噪音）
    for match in _QUOTED_RE.finditer(page_text):
        quoted = match.group(1)
        if quoted in companies or quoted in products or quoted in materials:
            add_candidate(quoted, match.start(1), match.end(1), "PRODUCT", "quoted")

    # 4. 产品正则兜底（要求边界）
    for match in _PRODUCT_RE.finditer(page_text):
        add_candidate(match.group(1), match.start(1), match.end(1), "PRODUCT", "regex")

    # 5. 原材料正则兜底（要求边界）
    for match in _MATERIAL_RE.finditer(page_text):
        add_candidate(match.group(1), match.start(1), match.end(1), "RAW_MATERIAL", "regex")

    # 同页同实体去重（保留置信度最高者）
    seen: dict[tuple[str, str], dict[str, Any]] = {}
    for fact in facts:
        key = (fact["entity"], fact["entity_type"])
        if key not in seen or fact["confidence"] > seen[key]["confidence"]:
            seen[key] = fact
    deduped = sorted(seen.values(), key=lambda item: item["confidence"], reverse=True)

    # 同页共现（公司 - 产品 / 原材料），用于图谱连线
    company_positions = [(name, pos) for name, entity_type, pos in positions if entity_type == "COMPANY"]
    product_positions = [(name, pos) for name, entity_type, pos in positions if entity_type in {"PRODUCT", "RAW_MATERIAL"}]
    seen_co: set[tuple[str, str]] = set()
    for company_name, company_position in company_positions:
        window_end = company_position + 260
        for product_name, product_position in product_positions:
            if product_position < company_position or product_position > window_end:
                continue
            key = (company_name, product_name)
            if key in seen_co:
                continue
            seen_co.add(key)
            cooccurrences.append(
                {
                    "company": company_name,
                    "product": product_name,
                    "evidence": _evidence_window(page_text, company_position, sentences, 160),
                    "page": page_index,
                }
            )

    return deduped, cooccurrences

def _extract_report(
    report_id: str,
    title: str,
    pages: list[str],
    file_name: str,
) -> tuple[dict[str, Any], list[str]]:
    """执行 解析 -> 抽取 -> 校验 -> 审阅 四个阶段，返回报告文档与警告。"""

    warnings: list[str] = []
    whitelist = _load_whitelist()
    full_text = "\n".join(pages)
    chars = len(full_text)
    if chars < MIN_TEXT_CHARS:
        warnings.append("文本过少，疑似扫描件，建议后续做 OCR")
    chains = _detect_chains_in_text(full_text, title)
    if not chains:
        chains = ["其他"]
        warnings.append("未命中产业链关键词，归入「其他」")
    primary_chain = chains[0]

    facts: list[dict[str, Any]] = []
    cooccurrences: list[dict[str, str]] = []
    for page_index, page_text in enumerate(pages, start=1):
        page_facts, page_co = _extract_facts_from_page(page_index, page_text, chains, primary_chain, whitelist)
        facts.extend(page_facts)
        cooccurrences.extend(page_co)

    # 去重并截断
    seen_facts: set[tuple[str, str, str, str]] = set()
    deduped: list[dict[str, Any]] = []
    for fact in facts:
        key = (fact["entity"], fact["entity_type"], fact["chain"], fact["stage"])
        if key in seen_facts:
            continue
        seen_facts.add(key)
        deduped.append(fact)
        if len(deduped) >= MAX_FACTS_PER_REPORT:
            break
    deduped.sort(key=lambda item: item["confidence"], reverse=True)

    seen_co: set[tuple[str, str]] = set()
    deduped_co: list[dict[str, str]] = []
    for item in cooccurrences:
        key = (item["company"], item["product"])
        if key in seen_co:
            continue
        seen_co.add(key)
        deduped_co.append(item)
        if len(deduped_co) >= 80:
            break

    if not deduped:
        warnings.append("未抽取到公司/产品事实")

    document: dict[str, Any] = {
        "schema_version": 1,
        "report_id": report_id,
        "file_name": file_name,
        "title": title,
        "status": STATUS_REVIEWED,
        "processed_at": _utcnow(),
        "pages": len(pages),
        "chars": chars,
        "primary_chain": primary_chain,
        "related_chains": chains[1:],
        "dates": _detect_dates(full_text),
        "chunks": _chunk_pages(pages),
        "facts": deduped,
        "cooccurrences": deduped_co,
        "warnings": warnings,
    }
    return document, warnings


def _process_one(
    pdf: Path,
    output_root: Path,
    version: int,
    *,
    force: bool = False,
    ocr_fallback: bool = True,
) -> dict[str, Any]:
    """处理单个 PDF；已完成且版本一致的篇目直接跳过（force=True 时忽略）。"""

    try:
        file_bytes = pdf.read_bytes()
        sha256 = hashlib.sha256(file_bytes).hexdigest()
    except OSError as error:
        return {
            "status": "failed",
            "file_name": pdf.name,
            "report_id": "",
            "facts": 0,
            "error": f"read failed: {error}",
        }
    report_id = f"report_{sha256[:16]}"
    output_path = output_root / f"{report_id}.json"
    if output_path.is_file() and not force:
        try:
            previous = json.loads(output_path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            previous = {}
        if (
            previous.get("status") in DONE_STATUSES
            and previous.get("version") == version
        ):
            return {
                "status": "skipped",
                "file_name": pdf.name,
                "report_id": report_id,
                "facts": len(previous.get("facts", [])),
            }

    if PdfReader is None:
        failed: dict[str, Any] = {
            "schema_version": 1,
            "report_id": report_id,
            "sha256": sha256,
            "file_name": pdf.name,
            "title": pdf.stem,
            "status": STATUS_FAILED,
            "version": version,
            "processed_at": _utcnow(),
            "pages": 0,
            "chars": 0,
            "facts": [],
            "cooccurrences": [],
            "warnings": ["pypdf 不可用，无法解析 PDF"],
            "error": "pypdf missing",
        }
        output_path.write_text(json.dumps(failed, ensure_ascii=False, indent=2), encoding="utf-8")
        return {"status": "failed", "file_name": pdf.name, "report_id": report_id, "facts": 0, "error": "pypdf missing"}

    try:
        reader = PdfReader(str(pdf))
        pages: list[str] = []
        for page in reader.pages:
            text = _clean_text(page.extract_text() or "")
            if text:
                pages.append(text)
    except Exception as error:  # noqa: BLE001 - 单篇解析失败不影响其他篇目
        failed = {
            "schema_version": 1,
            "report_id": report_id,
            "sha256": sha256,
            "file_name": pdf.name,
            "title": pdf.stem,
            "status": STATUS_FAILED,
            "version": version,
            "processed_at": _utcnow(),
            "pages": 0,
            "chars": 0,
            "facts": [],
            "cooccurrences": [],
            "warnings": [f"解析异常: {error}"],
            "error": str(error),
        }
        output_path.write_text(json.dumps(failed, ensure_ascii=False, indent=2), encoding="utf-8")
        return {
            "status": "failed",
            "file_name": pdf.name,
            "report_id": report_id,
            "facts": 0,
            "error": str(error),
        }

    ocr_applied = False
    plain_chars = sum(len(page) for page in pages)
    if ocr_fallback and plain_chars < MIN_TEXT_CHARS:
        try:
            from market_monitor.report_ocr import ocr_pdf_pages

            ocr_pages = ocr_pdf_pages(pdf)
            cleaned_ocr = [_clean_text(page) for page in ocr_pages]
            cleaned_ocr = [page for page in cleaned_ocr if page]
            ocr_chars = sum(len(page) for page in cleaned_ocr)
            if cleaned_ocr and ocr_chars > plain_chars:
                pages = cleaned_ocr
                ocr_applied = True
        except Exception:  # noqa: BLE001 - OCR 失败时保留原文本
            ocr_applied = False
            pages = pages

    title = pdf.stem
    title = re.sub(r"^\d{8}[-_]?", "", title)
    title = re.sub(r"^(.*?)-", r"\1", title, count=1)
    document, _ = _extract_report(report_id, title, pages, pdf.name)
    document["sha256"] = sha256
    document["version"] = version
    document["ocr_applied"] = ocr_applied
    if ocr_applied:
        document["warnings"].append("扫描件已通过 OCR 补偿解析")
    output_path.write_text(json.dumps(document, ensure_ascii=False, indent=2), encoding="utf-8")
    return {
        "status": "processed",
        "file_name": pdf.name,
        "report_id": report_id,
        "facts": len(document["facts"]),
        "ocr_applied": ocr_applied,
    }


def process_report_batch(
    report_root: Path,
    output_root: Path,
    *,
    workers: int = 4,
    limit: int = 0,
    version: int = 1,
    ocr_fallback: bool = True,
) -> dict[str, Any]:
    """并发处理研报目录下所有 PDF，返回批次汇总。"""

    report_root = Path(report_root)
    output_root = Path(output_root)
    output_root.mkdir(parents=True, exist_ok=True)
    pdfs = sorted(report_root.rglob("*.pdf"))
    if limit > 0:
        pdfs = pdfs[:limit]
    started_at = _utcnow()
    start_seconds = time.monotonic()

    if workers <= 1:
        results = [_process_one(pdf, output_root, version, ocr_fallback=ocr_fallback) for pdf in pdfs]
    else:
        with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
            results = list(
                pool.map(
                    lambda pdf: _process_one(pdf, output_root, version, ocr_fallback=ocr_fallback),
                    pdfs,
                )
            )

    processed = [item for item in results if item["status"] == "processed"]
    skipped = [item for item in results if item["status"] == "skipped"]
    failed = [item for item in results if item["status"] == "failed"]
    facts = sum(int(item.get("facts", 0)) for item in results)
    elapsed_seconds = round(time.monotonic() - start_seconds, 1)
    summary = {
        "report_root": str(report_root),
        "output_root": str(output_root),
        "version": version,
        "started_at": started_at,
        "completed_at": _utcnow(),
        "elapsed_seconds": elapsed_seconds,
        "total": len(pdfs),
        "processed": len(processed),
        "skipped": len(skipped),
        "failed": len(failed),
        "facts": facts,
        "failed_files": [item["file_name"] for item in failed],
    }
    (output_root / "batch_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return summary


def report_status_summary(output_root: Path) -> dict[str, Any]:
    """扫描报告产物目录，返回每篇状态、事实数与失败清单。"""

    output_root = Path(output_root)
    reports: list[dict[str, Any]] = []
    status_counts: Counter[str] = Counter()
    facts = 0
    chains: Counter[str] = Counter()
    for path in sorted(output_root.glob("report_*.json")):
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            status_counts["UNREADABLE"] += 1
            reports.append({"report_id": path.stem, "file_name": path.name, "status": "UNREADABLE"})
            continue
        status = str(document.get("status", "UNKNOWN"))
        status_counts[status] += 1
        report_facts = document.get("facts", [])
        facts += len(report_facts)
        chains[str(document.get("primary_chain", "其他"))] += 1
        reports.append(
            {
                "report_id": document.get("report_id", path.stem),
                "file_name": document.get("file_name", path.name),
                "status": status,
                "review_passed": document.get("review", {}).get("passed"),
                "chars": document.get("chars", 0),
                "pages": document.get("pages", 0),
                "facts": len(report_facts),
                "primary_chain": document.get("primary_chain", "其他"),
                "processed_at": document.get("processed_at", ""),
                "error": document.get("error"),
                "warnings": document.get("warnings", []),
            }
        )

    batch_summaries: list[dict[str, Any]] = []
    batch_path = output_root / "batch_summary.json"
    if batch_path.is_file():
        try:
            batch_summaries.append(json.loads(batch_path.read_text(encoding="utf-8")))
        except (OSError, ValueError):
            pass
    for path in sorted(output_root.glob("batch_summary_*.json")):
        try:
            batch_summaries.append(json.loads(path.read_text(encoding="utf-8")))
        except (OSError, ValueError):
            pass
    batch_summaries.sort(key=lambda item: item.get("started_at", ""), reverse=True)

    return {
        "output_root": str(output_root),
        "total": len(reports),
        "status_counts": dict(status_counts),
        "review_passed": sum(1 for item in reports if item.get("review_passed")),
        "review_failed": sum(1 for item in reports if item.get("review_passed") is False),
        "fact_count": facts,
        "chain_count": len(chains),
        "chain_distribution": dict(chains.most_common()),
        "reports": reports,
        "failed": [item for item in reports if item["status"] in {STATUS_FAILED, "UNREADABLE"}],
        "batches": batch_summaries[:20],
        "generated_at": _utcnow(),
    }


def verify_report_batch(
    output_root: Path,
    *,
    workers: int = 4,
) -> dict[str, Any]:
    """脚本化核验每篇研报（Web Verifier / Reviewer 的本地确定性版本）。

    核验项：JSON schema、事实实体类型、证据引用、产业链注册、共现完整性、
    警告数量。结果写入每篇 JSON 的 ``review`` 块，状态保留 REVIEWED，
    后续人工/联网核验可通过 ``review.passed`` 与 ``review.issues`` 追踪。
    """

    output_root = Path(output_root)
    paths = sorted(output_root.glob("report_*.json"))
    if workers <= 1:
        results = [_verify_one(path) for path in paths]
    else:
        with concurrent.futures.ThreadPoolExecutor(max_workers=workers) as pool:
            results = list(pool.map(_verify_one, paths))

    verified = [item for item in results if item.get("passed")]
    flagged = [item for item in results if not item.get("passed") and item.get("status") != "failed"]
    failed = [item for item in results if item.get("status") == "failed"]
    summary = {
        "output_root": str(output_root),
        "total": len(results),
        "passed": len(verified),
        "flagged": len(flagged),
        "failed": len(failed),
        "issues": [item for item in flagged[:50] if item.get("issues")],
        "failed_files": [item.get("file_name", item.get("report_id", "")) for item in failed],
        "generated_at": _utcnow(),
    }
    (output_root / "review_summary.json").write_text(
        json.dumps(summary, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return summary


def _verify_one(path: Path) -> dict[str, Any]:
    try:
        document = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as error:
        return {"status": "failed", "file_name": path.name, "report_id": path.stem, "error": str(error)}

    issues: list[str] = []
    checks: dict[str, bool] = {}

    checks["schema"] = document.get("schema_version") == 1 and bool(document.get("report_id"))
    if not checks["schema"]:
        issues.append("JSON schema 不完整")

    facts: list[dict[str, Any]] = document.get("facts", [])
    checks["facts"] = len(facts) > 0
    if not facts:
        issues.append("未抽取到任何事实")

    known_types = {"COMPANY", "PRODUCT", "RAW_MATERIAL"}
    bad_entity_types = sum(1 for fact in facts if fact.get("entity_type") not in known_types)
    missing_entity = sum(1 for fact in facts if not fact.get("entity"))
    checks["entity"] = bad_entity_types == 0 and missing_entity == 0
    if bad_entity_types:
        issues.append(f"{bad_entity_types} 条事实实体类型未注册")
    if missing_entity:
        issues.append(f"{missing_entity} 条事实缺少实体名")

    missing_evidence = sum(1 for fact in facts if not fact.get("evidence"))
    checks["evidence"] = missing_evidence == 0
    if missing_evidence:
        issues.append(f"{missing_evidence} 条事实缺少证据引用")

    unknown_chains = sum(
        1
        for fact in facts
        if fact.get("chain", "其他") not in CHAIN_REGISTRY and fact.get("chain") != "其他"
    )
    checks["chains"] = unknown_chains == 0
    if unknown_chains:
        issues.append(f"{unknown_chains} 条事实产业链未注册")

    cooccurrences: list[dict[str, Any]] = document.get("cooccurrences", [])
    bad_co = sum(1 for item in cooccurrences if not item.get("company") or not item.get("product"))
    checks["cooccurrences"] = bad_co == 0
    if bad_co:
        issues.append(f"{bad_co} 条共现实体缺失")

    warnings: list[str] = document.get("warnings", [])
    checks["warnings"] = len(warnings) <= 2
    if len(warnings) > 2:
        issues.append(f"警告过多（{len(warnings)} 条），建议人工复核")

    passed = all(checks.values())
    review = {
        "reviewed_at": _utcnow(),
        "reviewer": "scripted-rule-reviewer-v1",
        "passed": passed,
        "checks": checks,
        "issues": issues[:20],
        "warnings": warnings[:20],
    }
    document["review"] = review
    path.write_text(json.dumps(document, ensure_ascii=False, indent=2), encoding="utf-8")
    return {
        "status": "ok" if passed else "flagged",
        "passed": passed,
        "file_name": document.get("file_name", path.name),
        "report_id": document.get("report_id", path.stem),
        "facts": len(facts),
        "issues": issues[:20],
    }


def _aggregate_chains(output_root: Path, max_facts_per_chain: int) -> dict[str, Any]:
    """读取报告 JSON 并按产业链聚合。"""

    report_documents: list[dict[str, Any]] = []
    for path in sorted(output_root.glob("report_*.json")):
        try:
            document = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            continue
        if document.get("status") not in DONE_STATUSES:
            continue
        report_documents.append(document)

    chains: dict[str, dict[str, Any]] = defaultdict(
        lambda: {
            "chain": "",
            "report_count": 0,
            "fact_count": 0,
            "segments": Counter(),
            "companies": Counter(),
            "products": Counter(),
            "materials": Counter(),
            "services": Counter(),
            "facts": [],
            "reports": [],
            "cooccurrences": [],
        }
    )
    for document in report_documents:
        primary = str(document.get("primary_chain", "其他"))
        related = [str(item) for item in document.get("related_chains", [])]
        for chain in [primary, *related]:
            chain_data = chains[chain]
            chain_data["chain"] = chain
            chain_data["report_count"] += 1
            if chain == primary:
                chain_data["reports"].append(
                    {
                        "report_id": document.get("report_id", ""),
                        "file_name": document.get("file_name", ""),
                        "title": document.get("title", ""),
                        "processed_at": document.get("processed_at", ""),
                        "chars": document.get("chars", 0),
                        "pages": document.get("pages", 0),
                        "primary": True,
                    }
                )
            for fact in document.get("facts", []):
                if str(fact.get("chain", "")) != chain:
                    continue
                chain_data["fact_count"] += 1
                entity_type = str(fact.get("entity_type", ""))
                entity = str(fact.get("entity", ""))
                if entity_type == "COMPANY":
                    chain_data["companies"][entity] += 1
                elif entity_type == "PRODUCT":
                    chain_data["products"][entity] += 1
                elif entity_type == "RAW_MATERIAL":
                    chain_data["materials"][entity] += 1
                elif entity_type == "SERVICE":
                    chain_data["services"][entity] += 1
                segment = str(fact.get("segment", ""))
                if segment:
                    chain_data["segments"][segment] += 1
                chain_data["facts"].append(
                    {
                        "entity": entity,
                        "entity_type": entity_type,
                        "chain": chain,
                        "stage": str(fact.get("stage", "中游")),
                        "evidence": str(fact.get("evidence", ""))[:MAX_EVIDENCE_CHARS],
                        "page": fact.get("page"),
                        "confidence": float(fact.get("confidence", 0.5)),
                        "report_id": document.get("report_id", ""),
                        "file_name": document.get("file_name", ""),
                    }
                )
            for item in document.get("cooccurrences", []):
                if chain == primary:
                    chain_data["cooccurrences"].append(
                        {
                            "company": item.get("company", ""),
                            "product": item.get("product", ""),
                            "evidence": item.get("evidence", ""),
                            "page": item.get("page"),
                            "report_id": document.get("report_id", ""),
                            "file_name": document.get("file_name", ""),
                       }
                   )
    # Pass 2: include facts whose own chain field differs from
    # the document-declared primary/related chains.
    for document in report_documents:
        for fact in document.get("facts", []):
            fact_chain = str(fact.get("chain", ""))
            if not fact_chain:
                continue
            declared = [str(document.get("primary_chain", "其他"))]
            declared.extend(str(c) for c in document.get("related_chains", []))
            if fact_chain in declared:
                continue
            chain_data = chains[fact_chain]
            chain_data["chain"] = fact_chain
            chain_data["report_count"] += 1
            if fact_chain not in [r.get("report_id") for r in chain_data["reports"]]:
                chain_data["reports"].append({
                    "report_id": document.get("report_id", ""),
                    "file_name": document.get("file_name", ""),
                    "title": document.get("title", ""),
                    "processed_at": document.get("processed_at", ""),
                    "chars": document.get("chars", 0),
                    "pages": document.get("pages", 0),
                    "primary": False,
                })
            entity_type = str(fact.get("entity_type", ""))
            entity = str(fact.get("entity", ""))
            if entity_type == "COMPANY":
                chain_data["companies"][entity] += 1
            elif entity_type == "PRODUCT":
                chain_data["products"][entity] += 1
            elif entity_type == "RAW_MATERIAL":
                chain_data["materials"][entity] += 1
            elif entity_type == "SERVICE":
                chain_data["services"][entity] += 1
            segment = str(fact.get("segment", ""))
            if segment:
                chain_data["segments"][segment] += 1
            chain_data["fact_count"] += 1
            chain_data["facts"].append({
                "entity": entity,
                "entity_type": entity_type,
                "chain": fact_chain,
                "stage": str(fact.get("stage", "中游")),
                "evidence": str(fact.get("evidence", ""))[:MAX_EVIDENCE_CHARS],
                "page": fact.get("page"),
                "confidence": float(fact.get("confidence", 0.5)),
                "report_id": document.get("report_id", ""),
                "file_name": document.get("file_name", ""),
            })


    index_chains: list[dict[str, Any]] = []
    for chain, data in chains.items():
        if data["fact_count"] == 0 and data["report_count"] == 0:
            continue
        facts = sorted(data["facts"], key=lambda item: item["confidence"], reverse=True)
        index_chains.append(
            {
                "chain": chain,
                "report_count": data["report_count"],
                "fact_count": data["fact_count"],
                "segments": [{"name": name, "count": count} for name, count in data["segments"].most_common(30)],
                "companies": [{"name": name, "count": count} for name, count in data["companies"].most_common(60)],
                "products": [{"name": name, "count": count} for name, count in data["products"].most_common(40)],
                "materials": [{"name": name, "count": count} for name, count in data["materials"].most_common(20)],
                "services": [{"name": name, "count": count} for name, count in data["services"].most_common(15)],
                "facts": facts[:max_facts_per_chain],
                "reports": data["reports"][:80],
                "cooccurrences": data["cooccurrences"][:120],
            }
        )
    index_chains.sort(key=lambda item: item["report_count"], reverse=True)
    return {
        "generated_at": _utcnow(),
        "chain_count": len(index_chains),
        "report_count": len(report_documents),
        "fact_count": sum(int(item["fact_count"]) for item in index_chains),
        "chains": index_chains,
    }


def build_chain_index(output_root: Path, max_facts_per_chain: int = 200) -> dict[str, Any]:
    """Aggregate the preserved report facts into the canonical chain index JSON."""

    output_root = Path(output_root)
    index = _aggregate_chains(output_root, max_facts_per_chain)
    (output_root / "chain_index.json").write_text(
        json.dumps(index, ensure_ascii=False, indent=2),
        encoding="utf-8",
    )
    return index


